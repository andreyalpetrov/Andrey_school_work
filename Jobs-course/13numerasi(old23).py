# случай когда много условий и мы не должны попасть в какое-то чисто
#  пример: из 3 в 13, траектория без 8

def f(cur, end):
    if cur>end or cur == 8: return 0
    if cur == end: return 1
    else: return f(cur + 1, end) + f(cur + 2, end) + f(cur*2, end)

print(f(3,13))

