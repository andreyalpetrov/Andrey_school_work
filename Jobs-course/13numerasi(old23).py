# коварная задачка: из 1 в 38, нельзя числа с цифрой 6

def f(c,e):
    if c > e or '6' in str(c): return 0
    if c == e: return 1
    return f(c + 1, e) + f(c + 2, e) + f(c * 2, e)

print(f(1,38))


