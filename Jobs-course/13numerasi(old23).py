# ещё обратный случай, мы обязаны из 2 в 16 пройти через 14 !

def f(c,e):
    if c>e: return 0
    if c == e: return 1
    return f(c + 1, e) + f(c + 2, e) + f(c * 3, e)

print(f(2, 14)*f(14, 16))


